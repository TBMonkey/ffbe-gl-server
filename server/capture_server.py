# The tag whose per-mission keys hold our AUTHORED battle bundles (`<tag>@<mission>`), with the bare tag as
# the placeholder for every unauthored mission. Kept here (not imported from `harness/`) so the server has no
# build-time dependency on the derivation tool; `harness/derive_battle_payload.py` is the tool that writes them.
BATTLE_BUNDLE_REPLY_ID = "jnw49dUq"


class Handler(BaseHTTPRequestHandler):
    protocol_version = "HTTP/1.1"
    server_version = "ffbe-lab/0.1"

    def log_message(self, fmt, *args):  # silence the default stderr line; we log structurally
        pass

    def _handle(self):
        length = int(self.headers.get("Content-Length") or 0)
        raw = self.rfile.read(length) if length else b""
        body_text = raw.decode("utf-8", errors="replace")

        envelope = None
        header = {}
        ciphertext = None
        plaintext = None
        decrypt_error = None
        try:
            envelope = json.loads(body_text)
            header = envelope.get("TEAYk6R1", {}) or {}
            ciphertext = (envelope.get("t7n6cVWf") or {}).get("qrVcDe48")
        except Exception as exc:  # noqa: BLE001 - first contact may send anything
            decrypt_error = f"body not an envelope: {exc}"

        ep, how = endpoint_for(self.path, header.get("z5hB3P01"))
        token = self.path.rsplit("/", 1)[-1].removesuffix(".php")
        enc_key = ep["encode_key"] if ep else None
        if ciphertext and enc_key:
            try:
                plaintext = cbc_decrypt(key16(enc_key), ciphertext).decode("utf-8", errors="replace")
            except Exception as exc:  # noqa: BLE001
                decrypt_error = f"decrypt failed for key {enc_key}: {exc}"
        elif ciphertext and not enc_key:
            decrypt_error = f"no encode key known for token {token!r} (endpoints.json stale or rebuilt?)"

        # Build the reply BEFORE recording, so each record names exactly which variant was served.
        # (Audit 2026-09-17: variant<->outcome attribution was otherwise unprovable, because nothing
        # recorded the reply and the server log was truncated per run.)
        reply_id = header.get("z5hB3P01") or token
        # Per-mission dispatch. A battle bundle is content, keyed by MISSION, but responses.json is
        # keyed by requestID. So try `<reply_id>@<mission>` first, then fall back to `<reply_id>`. The
        # mission id comes from the request body: `DungeonResourceLoadMstListRequest` carries
        # `1zTjkp5B:[{6uIYE15X:<id>}]`, `MissionEndRequest` carries `jQsE54Iz:[{qo3PECw6:<id>}]`.
        spec = None
        spec_key = None
        st.NOTES.clear()
        # Pick up an edited payload without a restart (see reload_replies_if_changed for why this exists).
        reload_replies_if_changed()
        reload_season_if_changed()
        warn_if_source_is_newer()
        mid = mission_id_from(plaintext)
        if mid:
            spec = State.replies.get(f"{reply_id}@{mid}")
            if spec is not None:
                spec_key = f"{reply_id}@{mid}"
        # THE DERIVED-CONTENT PATH (APP-33). `responses.json` only holds the beats WE authored; every other
        # mission used to fall through to the bare placeholder and play its default battle. When the
        # per-mission key is absent and this is the battle-bundle carrier, assemble the mission's bundle
        # from the tracked index (or the per-area cache) instead. Authored wins ABOVE -- this block only
        # runs when no `@`-key exists -- and `BATTLE_DERIVE=off` disables it entirely (the golden control).
        bundle_source = None
        if (spec is None and mid and reply_id == BATTLE_BUNDLE_REPLY_ID
                and battle_content.derive_mode() != "off"):
            origin: dict = {}
            derived = battle_content.assemble(mid, authored=State.replies, origin=origin)
            if derived is not None:
                spec = derived
                # The pipeline's `is_battle_bundle` gate is an EXACT `f"{reply_id}@{mid}"` match and must
                # keep firing (it claims the mission's drop slot), so the derived bundle is selected under
                # the same key an authored one would be. `bundle_source` records the real origin.
                spec_key = f"{reply_id}@{mid}"
                bundle_source = origin.get("where")
        if spec is None:
            spec = State.replies.get(reply_id)
            spec_key = reply_id if spec is not None else None
            # THE BARE KEY IS A PLACEHOLDER, NOT A MATCH. Every authored battle beat is a `<tag>@<mission>`
            # entry, and the bare tag then serves THAT SAME default bundle to every mission we have not
            # authored -- so an unauthored story beat silently plays the default's battle (the Vortex one,
            # 2110401). It cost an operator report on 2026-10-07 and again on 2026-10-11 (Dalaknya Plains,
            # north = 1110501), because the reply is a valid body and nothing on the wire looks wrong. Say it
            # out loud, with the mission id, so the next one is a grep instead of a bug report.
            if spec is not None and mid and reply_id == BATTLE_BUNDLE_REPLY_ID:
                st.NOTES.append(
                    f"*** FALLBACK BUNDLE: mission {mid} has no authored bundle -- serving the DEFAULT "
                    f"({reply_id}, the Vortex battle). If the oracle has its phases: "
                    f"harness/derive_battle_payload.py --apply --keep-fallback {mid}")
        if spec is None and "_default" in State.replies:
            spec, spec_key = State.replies["_default"], "_default"
        # The whole reply transform chain, in its one load-bearing order -- now one call into
        # `reply_pipeline` (extracted 2026-09-26, a pure move; see its docstring and
        # docs/SERVER_REFACTOR_PLAN.md Phase 2). Everything that is the REQUEST's I/O rather than the
        # REPLY's construction -- dispatch, the hot-reload checks, the record, the envelope -- stays here.
        spec = reply_pipeline(spec, reply_id=reply_id, plaintext=plaintext, mid=mid, spec_key=spec_key)
        # NOTE: `json.dumps(None)` is the 4-char string "null" — an unconfigured endpoint must send NOTHING
        # (an empty body), not the literal null.
        body_plain = spec if isinstance(spec, str) else (None if spec is None else json.dumps(spec))
        b64 = ""
        if enc_key and body_plain is not None:
            # Which secret encrypts the REPLY is an open question: `parse` passes [RequestData vptr+0x28]
            # (getEncodeKey) as the decode key, but every reply we encrypt that way is rejected —
            # including a plaintext of `{}` — so test the alternatives.
            ktok = enc_key
            if State.reply_key == "reqid":
                ktok = reply_id
            elif State.reply_key == "reqid8":
                ktok = (reply_id or "")[:8]
            b64 = cbc_encrypt(key16(ktok), body_plain.encode(),
                              b"\x00" * 16 if State.reply_iv == "zero" else IV,
                              double_pad=State.double_pad)
        if State.echo_cipher and ciphertext:
            b64 = ciphertext
        hdr = {k: header.get(k) for k in ("z5hB3P01", "ytHoz4E2", "9K0Pzcpd") if header.get(k)}
        hdr["dNrSy63V"] = str(int(time.time()))

        # Envelope-shape bisect. The echo experiment (different plaintext, SAME envelope) also failed, so the
        # envelope is the common suspect; each mode isolates one structural assumption.
        mode = State.envelope
        if mode == "obj":                       # the original: t7n6cVWf object, then TEAYk6R1
            payload = {"t7n6cVWf": {"qrVcDe48": b64}}
            if not State.omit_header:
                payload["TEAYk6R1"] = hdr
        elif mode == "hdr_first":                # same keys, TEAYk6R1 emitted first in the JSON text
            payload = {}
            if not State.omit_header:
                payload["TEAYk6R1"] = hdr
            payload["t7n6cVWf"] = {"qrVcDe48": b64}
        elif mode == "arr":                      # t7n6cVWf as an ARRAY of one object (the group shape)
            payload = {"t7n6cVWf": [{"qrVcDe48": b64}]}
            if not State.omit_header:
                payload["TEAYk6R1"] = hdr
        elif mode == "noheader":                 # t7n6cVWf only
            payload = {"t7n6cVWf": {"qrVcDe48": b64}}
        elif mode == "headeronly":               # TEAYk6R1 only
            payload = {"TEAYk6R1": hdr}
        elif mode == "hdr_arr":                  # both as arrays of one object
            payload = {"t7n6cVWf": [{"qrVcDe48": b64}], "TEAYk6R1": [hdr]}
        else:
            raise SystemExit(f"unknown ENVELOPE mode {mode!r}")
        is_action = "/actionSymbol/" in self.path
        data = json.dumps(payload).encode() if is_action else b"{}"

        State.requests += 1
        rec = {
            "ts": time.strftime("%Y-%m-%dT%H:%M:%S%z"),
            "method": self.command,
            "path": self.path,
            "headers": dict(self.headers.items()),
            "body_len": len(raw),
            "header": header,
            "ciphertext_len": len(ciphertext) if ciphertext else 0,
            "endpoint": ep,
            "selected_by": how,
            "plaintext": plaintext,
            "decrypt_error": decrypt_error,
            "body_raw": body_text if not envelope else None,
            "reply": {
                "len": len(data),
                "sha256_16": hashlib.sha256(data).hexdigest()[:16],
                "envelope_keys": sorted(payload.keys()) if is_action else [],
                "reply_key": reply_id,
                "from_key": spec_key,
                "mission": mid,
                "body_plain_len": len(body_plain) if body_plain else 0,
                "flags": {"OMIT_HEADER": State.omit_header, "ECHO_CIPHER": State.echo_cipher,
                          "CLOSE_CONN": State.close_conn, "TLS12": State.tls12, "ENVELOPE": State.envelope,
                          "REPLY_KEY": State.reply_key, "REPLY_IV": State.reply_iv,
                          "LAPIS_AWARD": LAPIS_AWARD,
                          "DOUBLE_PAD": State.double_pad},
                "replies_from": os.path.basename(State.replies_path),
            },
        }
        os.makedirs(State.outdir, exist_ok=True)
        fname = os.path.join(State.outdir, f"{time.strftime('%Y%m%dT%H%M%S')}_{State.requests:04d}.json")
        if bundle_source:
            # Which layer answered a derived battle bundle (index vs cache) -- `from_key` alone cannot say,
            # because a derived bundle keeps the per-mission key for the pipeline gate.
            rec["reply"]["bundle_source"] = bundle_source
        with open(fname, "w", encoding="utf-8") as fh:
            json.dump(rec, fh, indent=1)

        flag = "OK " if plaintext else "?? "
        cls = ep["class"] if ep else "-"
        # Report WHICH key answered: `selected_by` describes the endpoint lookup, not the bundle dispatch,
        # so without this a per-mission fallback is invisible (audit_pad_parse.md C4 could not be settled
        # from the records for exactly that reason).
        # THE LABEL MUST DESCRIBE THE BODY, NOT THE DISPATCH KEY. It used to be
        # `reply:sent if spec_key is not None else reply:none`, i.e. "did a responses.json entry answer
        # this?" -- so a request served entirely by a TRANSFORM (the PANEL QUEST screen, which has no
        # responses.json entry) was logged `reply:none` while carrying a full body. That reads exactly like
        # the connection error it was mistaken for on 2026-09-26, and cost a triage cycle. Two facts, both
        # printed: was a body served, and which key (if any) selected it.
        replied = "reply:sent" if body_plain else "reply:EMPTY"
        replied += f" via {spec_key}" if spec_key else " via transform (no responses.json entry)"
        print(f"{flag}{self.command} {self.path}  class={cls} ({how})  key={enc_key}  "
              f"reqID={header.get('z5hB3P01')}  mission={mid or '-'}  from={spec_key or '-'}  "
              f"body={len(raw)}B  {replied}  -> {os.path.relpath(fname, WORK)}",
              flush=True)
        if plaintext:
            print("    plaintext: " + plaintext[:600].replace("\n", " "), flush=True)
        if decrypt_error:
            print("    note: " + decrypt_error, flush=True)
        for n in st.NOTES:
            print("    note: " + n, flush=True)
        st.NOTES.clear()

        self.send_response(200 if "/actionSymbol/" in self.path else 404)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(data)))
        if State.close_conn:
            self.send_header("Connection", "close")
            self.close_connection = True
        self.end_headers()
        self.wfile.write(data)

    # NOTE on ordering: these MUST come after any rebinding. A class body executes top to bottom, so an earlier
    # `def do_GET` is silently overwritten by a later `do_GET = _handle` — which is exactly what happened when
    # the CDN handler was first added above (it was dead code, and a CDN fetch was logged as an action call).
    do_POST = _handle

    def do_GET(self):
        self._cdn_fetch()

    def do_HEAD(self):
        self._cdn_fetch()

    def _cdn_fetch(self):
        """Serve a resource/CDN fetch from the shipped data tree, or 404 and say so.

        This axis matters as much as the API one: the client asks for its MST/resource files over a CDN path, and
        *what it asks for* is the whole unknown of the resource workstream. Two traps shaped this method:

        * without a handler at all, a GET reached BaseHTTPRequestHandler's default (501) and was never logged, so
          a download attempt looked like nothing happening;
        * the path carries the version **we** advertised -- the client asked for ``Ver1_i5QEJpua.dat`` when we said
          the MST version was 1, while the shipped file is ``Ver704_i5QEJpua.dat``. So the lookup falls back to
          the same token at whatever version we actually have, and logs that it did.

        Both cases are logged, so the request list stays the record of what the client wants.
        """
        path = self.path.split("?", 1)[0]
        # The client's fetch path mirrors its own on-disk layout under `files/`:
        #   /mst/Ver<N>_<token>.dat            -> files/mst/...
        #   /localized_texts/en/Ver<N>_<token>.dat -> files/localized_texts/en/...
        #   /en/sd/area/Ver<N>_x.cpk           -> files/en/sd/area/...
        # So serve the whole `files/` tree rather than a single subdirectory, and keep the
        # same-token fallback for the version-prefixed MST names only.
        rel = urllib.parse.unquote(path.lstrip("/"))     # the client percent-encodes spaces etc. in art names
        data = None
        how = None
        # --- authored web content -------------------------------------------------
        # The client's ToS / policy screens are WebViews that fetch HTML, observed live as
        # `GET //en/content/userpolicysin/index_a.html`. Those pages are NOT in the shipped tree (the real
        # client downloaded them from a CDN that no longer exists), so we serve an authored stand-in.
        # AUTHORED content, not recovered data -- COVERAGE_LEDGER.md §5.
        if rel.endswith(".html"):
            page = os.path.join(HERE, "webcontent", "userpolicy.html")
            if os.path.isfile(page):
                data, how = open(page, "rb").read(), "authored html stand-in"
        overlay = State.cdn_overlay
        if data is None and overlay and rel and ".." not in rel:
            exact = os.path.join(overlay, rel)
            if os.path.isfile(exact):
                data, how = open(exact, "rb").read(), "overlay"
        root = State.cdn_root
        if data is None and root and rel and ".." not in rel:
            exact = os.path.join(root, rel)
            if os.path.isfile(exact):
                data, how = open(exact, "rb").read(), "exact"
            else:
                # Same token, any Ver<N>_ prefix, looked up in the SAME directory as the request
                # (see the docstring: the advertised version and the shipped one can disagree).
                m = re.search(r"Ver\d+_([^/]+)\.dat$", rel)
                if m:
                    sub = os.path.dirname(rel)
                    hits = sorted(glob.glob(os.path.join(root, sub, f"Ver*_{m.group(1)}.dat")))
                    if len(hits) == 1:
                        data = open(hits[0], "rb").read()
                        how = "token-match " + os.path.basename(hits[0])
                    elif len(hits) > 1:
                        how = f"AMBIGUOUS ({len(hits)} candidates)"
        # ART BY BASENAME. The client stores art under its OWN names and the CPK trees are named
        # differently, so a basename lookup is the only join that works -- but the "banner" gate meant an
        # AREA art request (the gate/list tile art family, e.g. the spd_bn_list_* files under
        # area/Ver<N>_*/) never reached it and 404ed, leaving a tile that drew its frame with nothing in it
        # (operator report 2026-10-12). Both families are indexed; the verdict line says which answered.
        if data is None and rel and ".." not in rel \
                and os.path.splitext(rel)[1].lower() in (".png", ".jpg", ".jpeg") \
                and ("banner" in rel.lower() or "area" in rel.lower()):
            hit = banner_art_index().get(os.path.basename(rel)) if "banner" in rel.lower() else None
            how_art = "banner-art basename"
            if hit is None:
                hit = area_art_index().get(os.path.basename(rel))
                how_art = "area-art basename"
            if hit:
                data = open(hit, "rb").read()
                how = how_art + " (" + os.path.relpath(hit, os.path.dirname(WORK)) + ")"
        n = len(data) if data is not None else 0
        verdict = f"200 {n} B ({how})" if data is not None else f"404 ({how or 'not in the CDN root'})"
        print(f"CDN  {self.command} {self.path}  host={self.headers.get('Host')}  "
              f"ua={self.headers.get('User-Agent')}  -> {verdict}", flush=True)
        try:
            if data is None:
                self.send_response(404)
                self.send_header("Content-Length", "0")
                self.send_header("Connection", "close")
                self.end_headers()
            else:
                self.send_response(200)
                self.send_header("Content-Type", "application/octet-stream")
                self.send_header("Content-Length", str(n))
                self.send_header("Connection", "close")
                # end_headers() MUST come before the body, or the body is written into the header block and the
                # client sees a malformed response (caught by a curl test: server logged 200, client got 000).
                self.end_headers()
                if self.command != "HEAD":
                    self.wfile.write(data)
            self.close_connection = True
        except Exception:  # noqa: BLE001 -- the client may have gone away; nothing to do
            pass


def _proc_cmdlines() -> dict:
    """`{pid: cmdline}` for every readable /proc entry. No `pgrep`, so there is no self-match to fence."""
    out = {}
    for entry in os.listdir("/proc"):
        if not entry.isdigit():
            continue
        try:
            with open(f"/proc/{entry}/cmdline", "rb") as fh:
                out[entry] = fh.read().replace(b"\0", b" ").decode("utf-8", "replace")
        except OSError:
            continue
    return out


def _live_runs() -> list:
    """`[(pid, slot, autosaves)]` for every live `ffbe_run.sh` process.

    `slot` is the run's `--state` argument (`campaign` when absent -- the harness's SAVE_SLOT default), and
    `autosaves` is False for a `--no-autosave` run, which never writes its slot back at all. Only a run
    that would autosave ITS OWN slot can clobber a seed, so the caller matches slot names.
    """
    me = str(os.getpid())
    out = []
    for pid, cmd in _proc_cmdlines().items():
        if pid == me or "ffbe_run.sh" not in cmd:
            continue
        m = re.search(r"--state(?:=|\s+)(\S+)", cmd)
        out.append((pid, m.group(1) if m else "campaign", "--no-autosave" not in cmd))
    return out


def _target_slot(path: str) -> str | None:
    """The slot name a seed writes, for `out/state/<name>.json`; None for any other path (nothing writes it
    back, so nothing can clobber it)."""
    d, base = os.path.split(os.path.abspath(path))
    if os.path.basename(d) != "state" or not base.endswith(".json"):
        return None
    return base[: -len(".json")]


def _stale_servers() -> list:
    """Pids of `capture_server.py` processes other than this one -- noted, never blocking: they write
    `out/state.json`, never a slot, and the next run kills them when it claims :443."""
    me = str(os.getpid())
    return [pid for pid, cmd in _proc_cmdlines().items() if pid != me and "capture_server.py" in cmd]


def _seed_allowed(args) -> bool:
    """The slot-clobber guard shared by every `--grant-unit` form; False -> the caller returns 2.

    Refuses only when a live harness run would autosave the SAME slot (`_live_runs`): a run on another slot,
    or any `--no-autosave` run, cannot clobber the seed. A leftover capture_server from a finished run is
    only noted (it writes `out/state.json`, never a slot).
    """
    slot = _target_slot(st.STATE_FILE)
    blocking = [pid for pid, run_slot, autosaves in _live_runs()
                if autosaves and slot and run_slot == slot]
    if blocking and not args.force_seed:
        print(f"grant: REFUSING to seed -- a run on the same slot '{slot}' is live (pids "
              f"{', '.join(blocking)}); its end-of-run autosave will replace this seed.\n"
              f"       End it first (./harness/ffbe_run.sh --stop), or re-run with --force-seed.",
              file=sys.stderr)
        return False
    stale = _stale_servers()
    if stale:
        print(f"grant: note: a capture_server.py is still up from a finished run (pids "
              f"{', '.join(stale)}) -- it writes out/state.json, never this slot, and the next run "
              f"kills it when it claims :443.", file=sys.stderr)
    return True


def _seed_max_test_roster(args) -> int:
    """THE MAX TEST STATE -- the ONE seed shared by `--grant-unit all` and `--maxroster`.

    Added 2026-10-10 for the ability/effects tests against the Farplane dummy: one copy of every named
    unit series at its top named rarity, then EVERY roster row driven to its cap. `top_named_unit_rows`
    owns the family pick and `max_unit` owns the cap; this function only sequences them, so the CLI is a
    seed, not a second model. Returns 0 on success, 2 when the unit-name table yields no series.
    """
    rows = top_named_unit_rows(args.unit_rarity)
    if not rows:
        print("grant: no named F_UNIT_MST series -- is the unit-name text table readable?",
              file=sys.stderr)
        return 2
    for row in rows:
        State.player.grant_unit(str(row.get(UNIT_KEY)), granted_rarity=row.get("9fW0TePj"))
    # Max EVERY row, not just the granted ones: the default state's starters (and any row a slot
    # already carries) must not be the lone level-1 unit in a max test state.
    lvl = int(args.unit_level or 0)
    for u in list(State.player.data["roster"]):
        if lvl > 0:
            State.player.set_unit_level(u["instance_id"], lvl)
        else:
            State.player.max_unit(u["instance_id"])
    if lvl > 0:
        print(f"grant: --unit-level {lvl} pinned every roster row at level {lvl}", flush=True)
    if int(args.nv_ex or 0) > 0:
        n = 0
        for u in State.player.data["roster"]:
            if has_brave_shift(u["master_id"]):
                u["nv_ex_level"] = int(args.nv_ex)
                n += 1
        print(f"grant: --nv-ex {args.nv_ex} set on {n} Brave-Shift unit(s) "
              f"(served only with SERVE_NV_EX=1)", flush=True)
    State.player.save(st.STATE_FILE, force=True)
    roster = State.player.data["roster"]
    caps: dict = {}
    short = []
    for u in roster:
        cap = max_level(u["master_id"])
        caps[cap] = caps.get(cap, 0) + 1
        # The not-at-cap WARNING is meaningless in low mode (`--unit-level N`): every row is
        # DELIBERATELY below its cap there.
        if lvl == 0 and cap and int(u.get("level") or 0) != cap:
            short.append(str(u["instance_id"]))
    print(f"grant: ALL -- {len(rows)} named unit series -> roster {len(roster)}; "
          f"caps {dict(sorted(caps.items()))}", flush=True)
    if short:
        print(f"grant: WARNING {len(short)} row(s) not at their cap: {','.join(short[:5])}",
              file=sys.stderr)
    return 0


