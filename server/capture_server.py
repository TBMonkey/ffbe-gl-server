#!/usr/bin/env python3
"""capture_server.py — the synthetic FFBE (v9.0.0) server's first form: log, decrypt, reply.

Purpose on first contact: run it, point the client at it, and **observe which endpoint the client
actually calls first**. That empirically answers QUEUE SW-1 (the boot packet, currently only bounded
statically) and gives the real request body, which no static scan has produced yet.

It is deliberately dependency-free: TLS is Python's `ssl`; AES-128-CBC is the `openssl` CLI, the
same no-Python-crypto choice `scripts/mst_decode.py` makes for the MST corpus.

Recovered spec this implements (docs/analysis/FFBE_SERVER_CONTRACT.md §1e, high confidence):
  * request body = {"TEAYk6R1":<Header>, "t7n6cVWf":{"qrVcDe48":"<base64 ciphertext>"}}
    Header: ytHoz4E2=Milliseconds, z5hB3P01=RequestID, 9K0Pzcpd=AppVersion
  * ciphertext = AES-128-CBC/PKCS5(base64 outside), key = the request class's 8-char `EncodeKey`
    UTF-8 NUL-padded to 16, IV = the fixed literal `dZMjkk8gFDzKHlsx`
  * the key is chosen by the request class, which the URL token identifies -> out/endpoints.json
    (generated by harness/build_endpoints.py from the contract's §3 table; never hand-copied)

NOT recovered / do not assume: the **response** envelope's field names (payload-trees note,
unresolved #2). The default reply mirrors the request envelope; treat it as a probe, not a spec.

Usage:
    python3 server/capture_server.py --no-tls --port 8443            # local self-test
    sudo python3 server/capture_server.py --port 443 \
        --cert harness/certs/leaf.pem --key harness/certs/leaf.key
    python3 server/capture_server.py --data /path/to/ffbe-data       # run from a data root
    python3 server/capture_server.py --print-paths [--data DIR]      # resolved layout, then exit
    python3 server/capture_server.py --campaign                      # == --state campaign
    python3 server/capture_server.py --maxroster                     # == --state maxroster (+ seed)

THE DATA ROOT (`--data DIR`, or the `FFBE_DATA` env; `--data` wins) relocates every data path under one
directory: `mst_decoded/`, `text_decoded/`, `client/files/`, `client/shared_prefs/gamedata.xml`,
`cpk_extract/`, `overlay/`, `certs/`, `state/`. With no root set, the paths are exactly the
checkout-relative ones this server always used. `--print-paths` resolves the whole layout and prints one
`key=value` line per path -- it binds no port and does not load or write state, so it is safe to run
beside a live server. Granular overrides: `MST_DIR`, `TEXT_DIR`, `ART_ROOT` (new) plus the pre-existing
`CDN_ROOT`, `CDN_OVERLAY`, `VERSION_TABLE_XML`, `STATE_FILE`, `OUT_REQUESTS`; an explicit env value
always beats the root-relative path. The single resolver is `server/data_paths.py`.
"""
